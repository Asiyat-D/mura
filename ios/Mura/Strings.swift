struct Strings {
    let language: String
    subscript(key: T) -> String { translations[key]?[language == "kk" ? 1 : language == "en" ? 2 : 0] ?? key.rawValue }
    func failure(_ value: MuraError) -> String {
        let key: T = switch value {
        case .empty: .EmptyError
        case .format: .FormatError
        case .incomplete: .IncompleteError
        case .corrupted: .CorruptError
        case .tooLong: .LongError
        case .passwordShort: .PasswordError
        case .authentication: .AuthError
        case .storage: .StorageError
        case .qrTooLong: .QrError
        case .biometric: .BiometricUnavailable
        }
        return self[key]
    }
}
